// Local only: start anvil --chain-id 5042002 --port 8547, then run this script.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createPublicClient, createWalletClient, http, defineChain } from 'viem';

const rpc = 'http://127.0.0.1:8547';
const chain = defineChain({ id: 5042002, name: 'Local Arc simulation', nativeCurrency: { name: 'USDC', symbol: 'USDC', decimals: 18 }, rpcUrls: { default: { http: [rpc] } } });
const client = createPublicClient({ chain, transport: http(rpc) });
const wallet = createWalletClient({ chain, transport: http(rpc) });
assert.equal(await client.getChainId(), chain.id, 'Wrong local chain');
const [maker, taker] = await wallet.getAddresses();
assert.ok(maker && taker, 'Need two unlocked local accounts');
const artifact = (file, name) => JSON.parse(readFileSync(new URL(`../../contracts/out/${file}.sol/${name}.json`, import.meta.url)));
const pad = artifact('CurveLaunchpad', 'CurveLaunchpad');
const coin = artifact('CurveLaunchpad', 'CurveToken');
const bookArtifact = artifact('MofuOrderBook', 'MofuOrderBook');
const mined = async hash => { const receipt = await client.waitForTransactionReceipt({ hash }); assert.equal(receipt.status, 'success'); return receipt; };
const deploy = async (artifact, args = []) => (await mined(await wallet.deployContract({ account: maker, abi: artifact.abi, bytecode: artifact.bytecode.object, args }))).contractAddress;
const write = async (account, address, abi, functionName, args = [], value = 0n) => mined(await wallet.writeContract({ account, address, abi, functionName, args, value }));
const read = (address, abi, functionName, args = []) => client.readContract({ address, abi, functionName, args });
const factory = await deploy(pad);
const book = await deploy(bookArtifact, [factory]);
await write(maker, factory, pad.abi, 'createToken', ['Orderbook Coin', 'BOOK', 'Local integration test', '']);
const token = await read(factory, pad.abi, 'tokens', [0n]);
const cost = await read(token, coin.abi, 'quoteBuy', [1000n]);
await write(maker, token, coin.abi, 'buy', [1000n, cost, 9999999999n], cost);
await write(maker, token, coin.abi, 'approve', [book, 1000n * 10n ** 18n]);
await write(taker, token, coin.abi, 'approve', [book, 1000n * 10n ** 18n]);
const expiry = (await client.getBlock()).timestamp + 3600n;
const price = 10n ** 15n;
await write(maker, book, bookArtifact.abi, 'postOrder', [0n, false, 100n, price, expiry]);
await write(taker, book, bookArtifact.abi, 'fillOrder', [0n, 40n], 40n * price);
await write(maker, book, bookArtifact.abi, 'cancelOrder', [0n]);
assert.equal(await read(book, bookArtifact.abi, 'credits', [maker]), 40n * price);
await write(maker, book, bookArtifact.abi, 'withdraw');
await write(maker, book, bookArtifact.abi, 'postOrder', [0n, true, 30n, price, expiry], 30n * price);
await write(taker, book, bookArtifact.abi, 'fillOrder', [1n, 20n]);
await write(maker, book, bookArtifact.abi, 'cancelOrder', [1n]);
assert.equal(await read(book, bookArtifact.abi, 'credits', [maker]), 10n * price);
assert.equal(await read(book, bookArtifact.abi, 'credits', [taker]), 20n * price);
await write(maker, book, bookArtifact.abi, 'withdraw');
await write(taker, book, bookArtifact.abi, 'withdraw');
assert.equal(await client.getBalance({ address: book }), 0n);
assert.equal(await read(token, coin.abi, 'balanceOf', [book]), 0n);
assert.equal(await read(token, coin.abi, 'balanceOf', [maker]), 980n * 10n ** 18n);
assert.equal(await read(token, coin.abi, 'balanceOf', [taker]), 20n * 10n ** 18n);
console.log(JSON.stringify({ factory, book, token, result: 'PASS: deploy, curve buy, ask/bid partial fills, cancellations, withdrawals, token and native conservation' }));
